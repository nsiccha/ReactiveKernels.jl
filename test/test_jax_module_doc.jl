using ReactiveKernels
using Test

include(joinpath(@__DIR__, "jax_python.jl"))

# The module docstring (snag jax-source-modul-628c8468): the generated line
# comes first and stays; `doc`, the author's description of the program,
# follows it, and Python reads the authored text as written.

@kernel jax_module_doc_toy(x::Float64, s::Float64) = begin
    v = s * x^2
    return v
end

"""
    JAX_MODULE_DOC_TOY

A toy kernel: the scaled square of `x`, with angle ``\\theta``.
"""
const JAX_MODULE_DOC_TOY = jax_module_doc_toy

const JAX_MODULE_DOC_HEADER = "Generated by ReactiveKernels.jax_source; do not edit."

jax_module_doc_source(; kw...) =
    jax_source(jax_module_doc_toy; have = (:x, :s), want = :v, kw...)

@testset "jax_source: the module docstring" begin
    @testset "generated line alone without `doc`" begin
        src = jax_module_doc_source()
        @test startswith(string(src), "\"\"\"" * JAX_MODULE_DOC_HEADER * "\"\"\"\n")
        rk_test_python_docstring(src, JAX_MODULE_DOC_HEADER)
    end

    @testset "`doc` text follows the generated line" begin
        src = jax_module_doc_source(doc = "A toy kernel.")
        @test startswith(string(src),
                         "\"\"\"" * JAX_MODULE_DOC_HEADER * "\n\nA toy kernel.\n\"\"\"\n")
        rk_test_python_docstring(src, JAX_MODULE_DOC_HEADER * "\n\nA toy kernel.")
    end

    @testset "a binding's docstring, `@doc` Markdown" begin
        md = @doc(JAX_MODULE_DOC_TOY)
        src = jax_module_doc_source(doc = md)
        expected = JAX_MODULE_DOC_HEADER * "\n\n" * rstrip(string(md))
        @test occursin("A toy kernel: the scaled square of `x`", expected)
        @test occursin("\\theta", expected)
        rk_test_python_docstring(src, expected)
    end

    @testset "a `Plan`" begin
        p = plan(jax_module_doc_toy; have = (:x, :s), want = :v)
        rk_test_python_docstring(jax_source(p), JAX_MODULE_DOC_HEADER)
        rk_test_python_docstring(jax_source(p; doc = "Planned."),
                                 JAX_MODULE_DOC_HEADER * "\n\nPlanned.")
    end

    @testset "leading blank lines go; an indented signature stays" begin
        src = jax_module_doc_source(doc = "\n\n    SIGNATURE\n\nText.\n\n")
        rk_test_python_docstring(src, JAX_MODULE_DOC_HEADER * "\n\n    SIGNATURE\n\nText.")
    end

    # Backslashes (`\t` would be a tab, `\s` an invalid escape) and quotes
    # that could close the string are escaped, in the module docstring and in
    # a single-line function docstring that ends with a quote; the driver
    # parses the whole module with every warning an error.
    @testset "backslashes and quotes kept as written" begin
        authored = "Angles \\theta and \\sigma; a \"\"\"\" run; a line end \\\nends \"quoted\""
        src = jax_module_doc_source(doc = authored,
                                    function_docs = (kernel = "Returns \"v\"",))
        @test occursin("\\\\theta", string(src))
        rk_test_python_docstring(src, JAX_MODULE_DOC_HEADER * "\n\n" * authored)
        @test occursin("\"\"\"Returns \"v\\\"\"\"\"", string(src))
    end

    @testset "a frontend's complete docstring" begin
        src = jax_module_doc_source(module_docstring = "Generated by a frontend; do not edit.")
        rk_test_python_docstring(src, "Generated by a frontend; do not edit.")
        @test_throws ArgumentError jax_module_doc_source(doc = "A", module_docstring = "B")
    end
end
