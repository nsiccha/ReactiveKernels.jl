using ReactiveKernels, ReactiveKernelsPPL, Test

include(joinpath(pkgdir(ReactiveKernels), "test", "jax_python.jl"))

# The module docstring of a built @rkppl program (snag
# jax-source-modul-628c8468): `doc`, the author's description of the model,
# follows the generated line, and the generated `Data:` and
# `Model documentation:` sections stay after it.

"""
    JAX_MODULE_DOC_MODEL

A toy model: a level with a normal prior, observations around it.
"""
const JAX_MODULE_DOC_MODEL = @rkppl begin
    "Level."
    level ~ Normal(level_loc, level_scale)
    "Observations."
    y .~ Normal.(level, 1.0)
end

const JAX_MODULE_DOC_GENERATED =
    "Generated by ReactiveKernelsPPL.jax_source from a built @rkppl program; do not edit."
const JAX_MODULE_DOC_SECTIONS = "Data: level_loc, level_scale, y.\n\n" *
    "Model documentation:\n\n- `level`: Level.\n- `y`: Observations."

@testset "jax_source(built, plan): the module docstring" begin
    plan = JAX_MODULE_DOC_MODEL(; level_loc = 0.0, level_scale = 1.0) |
        (; y = [0.1, -0.3, 0.5])
    built = build_kernel(plan)

    plain = jax_source(built, plan)
    @test startswith(string(plain), "\"\"\"" * JAX_MODULE_DOC_GENERATED * "\n\n" *
                                    JAX_MODULE_DOC_SECTIONS * "\n\"\"\"\n")
    rk_test_python_docstring(plain, JAX_MODULE_DOC_GENERATED * "\n\n" * JAX_MODULE_DOC_SECTIONS)

    text = "A toy model: a level with a normal prior."
    rk_test_python_docstring(jax_source(built, plan; doc = text),
                             JAX_MODULE_DOC_GENERATED * "\n\n" * text * "\n\n" *
                             JAX_MODULE_DOC_SECTIONS)

    # The binding's own docstring, as `@doc` Markdown.
    md = @doc(JAX_MODULE_DOC_MODEL)
    authored = rstrip(string(md))
    @test occursin("A toy model: a level with a normal prior", authored)
    src = jax_source(built, plan; doc = md)
    @test count("Generated by", string(src)) == 1
    rk_test_python_docstring(src, JAX_MODULE_DOC_GENERATED * "\n\n" * authored * "\n\n" *
                                  JAX_MODULE_DOC_SECTIONS)
end
